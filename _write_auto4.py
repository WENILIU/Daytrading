import pathlib

path = pathlib.Path(r'C:\Users\weni.liu\Documents\Codex\2026-10-14\new-chat-3\outputs\gap_fade_auto.py')

lines = []
lines.append('')
lines.append('    # ----------------------------------------------------------')
lines.append('    # STEP 3: REAL-TIME MONITORING')
lines.append('    # ----------------------------------------------------------')
lines.append('')
lines.append('    def monitor_positions(self):')
lines.append('        """Real-time monitoring: auto-exit on SL/TP/force close"""')
lines.append('        self.log.info("=" * 60)')
lines.append('        self.log.info("STEP 3: Monitoring positions...")')
lines.append('        self.log.info(f"  Force exit at {self.config.force_exit_time}")')
lines.append('')
lines.append('        force_exit_dt = self._parse_time(self.config.force_exit_time)')
lines.append('')
lines.append('        while self.running:')
lines.append('            now = datetime.now()')
lines.append('')
lines.append('            # Check force exit time')
lines.append('            if now >= force_exit_dt:')
lines.append('                self.log.info("  FORCE EXIT TIME REACHED")')
lines.append('                self._force_close_all()')
lines.append('                break')
lines.append('')
lines.append('            # Check each position')
lines.append('            for symbol, sig in list(self.active_positions.items()):')
lines.append('                if sig.state not in (PositionState.FILLED, PositionState.MONITORING):')
lines.append('                    continue')
lines.append('')
lines.append('                sig.state = PositionState.MONITORING')
lines.append('')
lines.append('                # Get current price')
lines.append('                try:')
lines.append('                    quote = self.api.quote(f"{symbol}.TW")')
lines.append('                    current_price = float(quote.close)')
lines.append('                except Exception:')
lines.append('                    continue')
lines.append('')
lines.append('                # Check SL/TP')
lines.append('                should_exit = False')
lines.append('                reason = ""')
lines.append('')
lines.append('                if sig.direction == Direction.SHORT:')
lines.append('                    if current_price >= sig.sl_price:')
lines.append('                        should_exit = True')
lines.append('                        reason = "STOP_LOSS"')
lines.append('                    elif current_price <= sig.tp_price:')
lines.append('                        should_exit = True')
lines.append('                        reason = "TAKE_PROFIT"')
lines.append('                else:')
lines.append('                    if current_price <= sig.sl_price:')
lines.append('                        should_exit = True')
lines.append('                        reason = "STOP_LOSS"')
lines.append('                    elif current_price >= sig.tp_price:')
lines.append('                        should_exit = True')
lines.append('                        reason = "TAKE_PROFIT"')
lines.append('')
lines.append('                if should_exit:')
lines.append('                    self._close_position(sig, current_price, reason)')
lines.append('')
lines.append('            # Poll every 3 seconds')
lines.append('            time.sleep(3)')
lines.append('')
lines.append('    def _close_position(self, sig: Signal, price: float, reason: str):')
lines.append('        """Auto-close position"""')
lines.append('        try:')
lines.append('            contract = self.api.contracts.stock[sig.symbol]')
lines.append('        except KeyError:')
lines.append('            return')
lines.append('')
lines.append('        if sig.direction == Direction.SHORT:')
lines.append('            action = sj.Action.Buy')
lines.append('        else:')
lines.append('            action = sj.Action.Sell')
lines.append('')
lines.append('        order = sj.StockOrder(')
lines.append('            action=action,')
lines.append('            price=price,')
lines.append('            quantity=sig.shares,')
lines.append('            price_type=sj.StockPriceType.LMT,')
lines.append('            order_type=sj.OrderType.ROD,')
lines.append('            daytrade_short=False,')
lines.append('            order_lot=sj.StockOrderLot.Common,')
lines.append('        )')
lines.append('')
lines.append('        try:')
lines.append('            trade = self.api.place_order(contract=contract, order=order)')
lines.append('            sig.exit_price = price')
lines.append('            sig.exit_reason = reason')
lines.append('            sig.state = PositionState.EXITED')
lines.append('')
lines.append('            # Calculate PnL')
lines.append('            if sig.direction == Direction.SHORT:')
lines.append('                sig.pnl = (sig.entry_price - price) * sig.shares')
lines.append('            else:')
lines.append('                sig.pnl = (price - sig.entry_price) * sig.shares')
lines.append('            sig.pnl -= (sig.entry_price + price) * sig.shares * self.config.cost_per_trade')
lines.append('')
lines.append('            self.log.info(')
lines.append('                f"  EXIT: {sig.symbol} {sig.direction.value} @ {price} "')
lines.append('                f"[{reason}] PnL={sig.pnl:+,.0f}"')
lines.append('            )')
lines.append('')
lines.append('            self.closed_trades.append({')
lines.append('                "time": datetime.now().isoformat(),')
lines.append('                "symbol": sig.symbol, "name": sig.name,')
lines.append('                "direction": sig.direction.value, "tier": sig.tier,')
lines.append('                "shares": sig.shares, "entry": sig.entry_price,')
lines.append('                "exit": price, "reason": reason, "pnl": sig.pnl,')
lines.append('            })')
lines.append('            del self.active_positions[sig.symbol]')
lines.append('')
lines.append('        except Exception as e:')
lines.append('            self.log.error(f"  {sig.symbol}: close failed - {e}")')
lines.append('')
lines.append('    def _force_close_all(self):')
lines.append('        """13:25 force close all positions"""')
lines.append('        for symbol, sig in list(self.active_positions.items()):')
lines.append('            if sig.state in (PositionState.FILLED, PositionState.MONITORING):')
lines.append('                try:')
lines.append('                    quote = self.api.quote(f"{symbol}.TW")')
lines.append('                    price = float(quote.close)')
lines.append('                except Exception:')
lines.append('                    price = sig.entry_price')
lines.append('                self._close_position(sig, price, "FORCE_CLOSE")')
lines.append('')
lines.append('    # ----------------------------------------------------------')
lines.append('    # STEP 4: REPORT')
lines.append('    # ----------------------------------------------------------')
lines.append('')
lines.append('    def daily_report(self):')
lines.append('        """Daily settlement report"""')
lines.append('        self.log.info("=" * 60)')
lines.append('        self.log.info("DAILY REPORT")')
lines.append('')
lines.append('        if not self.closed_trades:')
lines.append('            self.log.info("  No trades today.")')
lines.append('            return')
lines.append('')
lines.append('        df = pd.DataFrame(self.closed_trades)')
lines.append('        total_pnl = df["pnl"].sum()')
lines.append('        wins = (df["pnl"] > 0).sum()')
lines.append('        total = len(df)')
lines.append('')
lines.append('        self.log.info(f"  Trades: {total}")')
lines.append('        self.log.info(f"  Win rate: {wins}/{total} ({wins/total*100:.1f}%)")')
lines.append('        self.log.info(f"  Total PnL: {total_pnl:+,.0f}")')
lines.append('        self.log.info(f"  Avg PnL: {total_pnl/total:+,.0f}")')
lines.append('')
lines.append('        # Save CSV')
lines.append('        today = datetime.now().strftime("%Y-%m-%d")')
lines.append('        csv_path = self.config.log_dir / f"trades_{today}.csv"')
lines.append('        df.to_csv(csv_path, index=False, encoding="utf-8-sig")')
lines.append('        self.log.info(f"  Saved: {csv_path}")')

