import pathlib

path = pathlib.Path(r'C:\Users\weni.liu\Documents\Codex\2026-10-14\new-chat-3\outputs\gap_fade_auto.py')

lines = []
lines.append('')
lines.append('    # ----------------------------------------------------------')
lines.append('    # STEP 1: 9:00 SCAN (Fugle API for bulk speed)')
lines.append('    # ----------------------------------------------------------')
lines.append('')
lines.append('    def scan_signals(self) -> list[Signal]:')
lines.append('        """9:00 scan all stocks for gap signals"""')
lines.append('        from fugle_marketdata import RestClient')
lines.append('')
lines.append('        self.log.info("=" * 60)')
lines.append('        self.log.info("STEP 1: Scanning signals...")')
lines.append('')
lines.append('        client = RestClient(api_key=self.config.fugle_api_key)')
lines.append('        stock = client.stock')
lines.append('')
lines.append('        # Get TAIEX gap')
lines.append('        try:')
lines.append('            index_data = stock.intraday.current(symbol="0000")')
lines.append('            self.market_gap = index_data.get("changePercent", 0) / 100')
lines.append('        except Exception:')
lines.append('            self.market_gap = 0.0')
lines.append('')
lines.append('        self.log.info(f"  Market gap: {self.market_gap*100:+.2f}%")')
lines.append('')
lines.append('        # Get all tickers')
lines.append('        tickers = stock.intraday.tickers(type="EQUITY", exchange="TWSE", isNormal=True)')
lines.append('')
lines.append('        candidates = []')
lines.append('        for ticker in tickers["data"]:')
lines.append('            symbol = ticker["symbol"]')
lines.append('            name = ticker["name"]')
lines.append('            open_price = ticker.get("open", 0)')
lines.append('            prev_close = ticker.get("previousClose", 0)')
lines.append('')
lines.append('            if prev_close < self.config.min_price or prev_close > self.config.max_price:')
lines.append('                continue')
lines.append('')
lines.append('            raw_gap = (open_price - prev_close) / prev_close if prev_close > 0 else 0')
lines.append('            adj_gap = raw_gap - self.market_gap')
lines.append('')
lines.append('            direction = None')
lines.append('            if adj_gap > self.config.gap_threshold:')
lines.append('                direction = Direction.SHORT')
lines.append('            elif adj_gap < -self.config.gap_threshold:')
lines.append('                direction = Direction.LONG')
lines.append('')
lines.append('            if direction is None:')
lines.append('                continue')
lines.append('')
lines.append('            candidates.append(Signal(')
lines.append('                symbol=symbol, name=name, direction=direction,')
lines.append('                open_price=open_price, prev_close=prev_close,')
lines.append('                raw_gap=raw_gap, adj_gap=adj_gap,')
lines.append('            ))')
lines.append('')
lines.append('        # Sort by |adj_gap|, take top N')
lines.append('        candidates.sort(key=lambda s: abs(s.adj_gap), reverse=True)')
lines.append('        self.signals = candidates[:self.config.max_daily_positions]')
lines.append('')
lines.append('        self.log.info(f"  Found {len(self.signals)} signals:")')
lines.append('        for s in self.signals:')
lines.append('            self.log.info(f"    {s.symbol} {s.name:<8} {s.direction.value:<5} gap={s.adj_gap*100:+.1f}%")')
lines.append('')
lines.append('        return self.signals')
lines.append('')
lines.append('    # ----------------------------------------------------------')
lines.append('    # STEP 2: 9:15 CONFIRM + AUTO ORDER')
lines.append('    # ----------------------------------------------------------')
lines.append('')
lines.append('    def confirm_and_enter(self):')
lines.append('        """9:15 confirm signals and auto-place orders"""')
lines.append('        self.log.info("=" * 60)')
lines.append('        self.log.info("STEP 2: Confirming & placing orders...")')
lines.append('')
lines.append('        # Subscribe to signals for real-time price')
lines.append('        symbols = [s.symbol for s in self.signals]')
lines.append('        self.api.subscribe(symbols)')
lines.append('        time.sleep(2)')
lines.append('')
lines.append('        total_exposure = 0')
lines.append('')
lines.append('        for sig in self.signals:')
lines.append('            # Get current price via shioaji quote')
lines.append('            try:')
lines.append('                quote = self.api.quote(f"{sig.symbol}.TW")')
lines.append('                current_price = float(quote.close)')
lines.append('            except Exception as e:')
lines.append('                self.log.warning(f"  {sig.symbol}: quote failed ({e}), skip")')
lines.append('                continue')
lines.append('')
lines.append('            # Calculate 15-min move')
lines.append('            if sig.direction == Direction.SHORT:')
lines.append('                drop_pct = (sig.open_price - current_price) / sig.open_price')
lines.append('            else:')
lines.append('                drop_pct = (current_price - sig.open_price) / sig.open_price')
lines.append('')
lines.append('            # Check confirmation')
lines.append('            if drop_pct <= self.config.confirm_drop_min:')
lines.append('                self.log.info(f"  {sig.symbol}: NOT confirmed (move={drop_pct*100:+.2f}%), SKIP")')
lines.append('                sig.state = PositionState.CANCELLED')
lines.append('                continue')
lines.append('')
lines.append('            # Determine tier')
lines.append('            for min_drop, max_drop, mult, label in self.config.tiers:')
lines.append('                if min_drop <= drop_pct < max_drop:')
lines.append('                    sig.tier = label')
lines.append('                    sig.tier_multiplier = mult')
lines.append('                    break')
lines.append('')
lines.append('            if sig.tier == "":')
lines.append('                continue')
lines.append('')
lines.append('            # Calculate position')
lines.append('            if sig.direction == Direction.SHORT:')
lines.append('                base_value = self.config.capital * self.config.base_position_pct')
lines.append('            else:')
lines.append('                base_value = self.config.capital * self.config.long_position_pct')
lines.append('')
lines.append('            position_value = base_value * sig.tier_multiplier')
lines.append('            shares = int(position_value / current_price / 1000) * 1000')
lines.append('')
lines.append('            if shares < 1000:')
lines.append('                self.log.info(f"  {sig.symbol}: < 1 zhang, SKIP")')
lines.append('                continue')
lines.append('')
lines.append('            # Check exposure limit')
lines.append('            actual_value = shares * current_price')
lines.append('            if total_exposure + actual_value > self.config.capital * self.config.max_daily_exposure:')
lines.append('                self.log.info(f"  {sig.symbol}: exposure limit, SKIP")')
lines.append('                continue')
lines.append('')
lines.append('            total_exposure += actual_value')
lines.append('')
lines.append('            # Set entry/SL/TP')
lines.append('            sig.entry_price = current_price')
lines.append('            sig.shares = shares')
lines.append('')
lines.append('            if sig.direction == Direction.SHORT:')
lines.append('                sig.sl_price = round(current_price * (1 + self.config.stop_loss_pct), 1)')
lines.append('                sig.tp_price = round(current_price * (1 - self.config.take_profit_pct), 1)')
lines.append('            else:')
lines.append('                sig.sl_price = round(current_price * (1 - self.config.stop_loss_pct), 1)')
lines.append('                sig.tp_price = round(current_price * (1 + self.config.take_profit_pct), 1)')
lines.append('')
lines.append('            # Place order')
lines.append('            self._place_entry_order(sig)')
lines.append('')
lines.append('        self.log.info(f"  Total exposure: {total_exposure:,.0f} ({total_exposure/self.config.capital*100:.0f}%)")')
lines.append('')
lines.append('    def _place_entry_order(self, sig: Signal):')
lines.append('        """Auto-place entry order via shioaji"""')
lines.append('        try:')
lines.append('            contract = self.api.contracts.stock[sig.symbol]')
lines.append('        except KeyError:')
lines.append('            self.log.error(f"  {sig.symbol}: contract not found")')
lines.append('            return')
lines.append('')
lines.append('        if sig.direction == Direction.SHORT:')
lines.append('            action = sj.Action.Sell')
lines.append('        else:')
lines.append('            action = sj.Action.Buy')
lines.append('')
lines.append('        order = sj.StockOrder(')
lines.append('            action=action,')
lines.append('            price=sig.entry_price,')
lines.append('            quantity=sig.shares,')
lines.append('            price_type=sj.StockPriceType.LMT,')
lines.append('            order_type=sj.OrderType.ROD,')
lines.append('            daytrade_short=(sig.direction == Direction.SHORT),')
lines.append('            order_lot=sj.StockOrderLot.Common,')
lines.append('        )')
lines.append('')
lines.append('        try:')
lines.append('            trade = self.api.place_order(contract=contract, order=order)')
lines.append('            sig.order_id = trade.id')
lines.append('            sig.state = PositionState.ORDERED')
lines.append('            self.active_positions[sig.symbol] = sig')
lines.append('            self.log.info(')
lines.append('                f"  ORDERED: {sig.symbol} {sig.direction.value} {sig.shares} shares "')
lines.append('                f"@ {sig.entry_price} [{sig.tier}] SL={sig.sl_price} TP={sig.tp_price}"')
lines.append('            )')
lines.append('        except Exception as e:')
lines.append('            self.log.error(f"  {sig.symbol}: order failed - {e}")')
lines.append('            sig.state = PositionState.CANCELLED')

path.write_text(
    path.read_text(encoding='utf-8') + '\n'.join(lines),
    encoding='utf-8'
)
print(f'Appended. Total: {path.stat().st_size} bytes')
