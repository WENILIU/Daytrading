import pathlib

path = pathlib.Path(r'C:\Users\weni.liu\Documents\Codex\2026-10-14\new-chat-3\outputs\gap_fade_auto.py')

lines = []
lines.append('')
lines.append('')
lines.append('# ============================================================')
lines.append('# DATA STRUCTURES')
lines.append('# ============================================================')
lines.append('')
lines.append('class Direction(Enum):')
lines.append('    SHORT = "SHORT"')
lines.append('    LONG = "LONG"')
lines.append('')
lines.append('')
lines.append('class PositionState(Enum):')
lines.append('    PENDING = "PENDING"')
lines.append('    CONFIRMED = "CONFIRMED"')
lines.append('    ORDERED = "ORDERED"')
lines.append('    FILLED = "FILLED"')
lines.append('    MONITORING = "MONITORING"')
lines.append('    EXITED = "EXITED"')
lines.append('    CANCELLED = "CANCELLED"')
lines.append('')
lines.append('')
lines.append('@dataclass')
lines.append('class Signal:')
lines.append('    symbol: str')
lines.append('    name: str')
lines.append('    direction: Direction')
lines.append('    open_price: float')
lines.append('    prev_close: float')
lines.append('    raw_gap: float')
lines.append('    adj_gap: float')
lines.append('    state: PositionState = PositionState.PENDING')
lines.append('    tier: str = ""')
lines.append('    tier_multiplier: float = 0.0')
lines.append('    shares: int = 0')
lines.append('    entry_price: float = 0.0')
lines.append('    sl_price: float = 0.0')
lines.append('    tp_price: float = 0.0')
lines.append('    order_id: str = ""')
lines.append('    fill_price: float = 0.0')
lines.append('    exit_price: float = 0.0')
lines.append('    exit_reason: str = ""')
lines.append('    pnl: float = 0.0')
lines.append('')
lines.append('')
lines.append('# ============================================================')
lines.append('# TRADING ENGINE')
lines.append('# ============================================================')
lines.append('')
lines.append('class GapFadeAutoTrader:')
lines.append('    def __init__(self, config: Config):')
lines.append('        self.config = config')
lines.append('        self.api: Optional[sj.Shioaji] = None')
lines.append('        self.signals: list[Signal] = []')
lines.append('        self.active_positions: dict[str, Signal] = {}')
lines.append('        self.closed_trades: list[dict] = []')
lines.append('        self.running = False')
lines.append('        self.market_gap = 0.0')
lines.append('')
lines.append('        # Setup logging')
lines.append('        config.log_dir.mkdir(parents=True, exist_ok=True)')
lines.append('        today = datetime.now().strftime("%Y-%m-%d")')
lines.append('        log_file = config.log_dir / f"trading_{today}.log"')
lines.append('')
lines.append('        logging.basicConfig(')
lines.append('            level=logging.INFO,')
lines.append('            format="%(asctime)s [%(levelname)s] %(message)s",')
lines.append('            handlers=[')
lines.append('                logging.FileHandler(log_file, encoding="utf-8"),')
lines.append('                logging.StreamHandler()')
lines.append('            ]')
lines.append('        )')
lines.append('        self.log = logging.getLogger("GapFade")')
lines.append('')
lines.append('    # ----------------------------------------------------------')
lines.append('    # CONNECTION')
lines.append('    # ----------------------------------------------------------')
lines.append('')
lines.append('    def connect(self):')
lines.append('        """Connect to Yuanta Securities API"""')
lines.append('        self.log.info("Connecting to Yuanta Securities...")')
lines.append('        self.api = sj.Shioaji(simulation=False)')
lines.append('        self.api.login(')
lines.append('            api_key=self.config.api_key,')
lines.append('            secret_key=self.config.secret_key')
lines.append('        )')
lines.append('        self.api.activate_ca(')
lines.append('            ca_path=self.config.ca_path,')
lines.append('            ca_passwd=self.config.ca_passwd')
lines.append('        )')
lines.append('        self.api.fetch_contracts()')
lines.append('        self.log.info("Connected. Contracts loaded.")')
lines.append('')
lines.append('        # Register order callback')
lines.append('        self.api.on_order(self._on_order_update)')
lines.append('        self.log.info("Order callback registered.")')
lines.append('')
lines.append('    def disconnect(self):')
lines.append('        if self.api:')
lines.append('            self.api.logout()')
lines.append('            self.log.info("Disconnected.")')
lines.append('')
lines.append('    def _on_order_update(self, event):')
lines.append('        """Callback: order status update"""')
lines.append('        order_id = event.id')
lines.append('        status = event.status')
lines.append('        self.log.info(f"Order {order_id}: {status}")')
lines.append('')
lines.append('        for sig in self.active_positions.values():')
lines.append('            if sig.order_id == order_id:')
lines.append('                if "filled" in str(status).lower():')
lines.append('                    sig.state = PositionState.FILLED')
lines.append('                    if hasattr(event, "deal_price") and event.deal_price:')
lines.append('                        sig.fill_price = float(event.deal_price)')
lines.append('                    else:')
lines.append('                        sig.fill_price = sig.entry_price')
lines.append('                    self.log.info(')
lines.append('                        f"  FILLED: {sig.symbol} {sig.direction.value} "')
lines.append('                        f"{sig.shares} shares @ {sig.fill_price}"')
lines.append('                    )')
lines.append('                elif "cancel" in str(status).lower():')
lines.append('                    sig.state = PositionState.CANCELLED')
lines.append('                    self.log.info(f"  CANCELLED: {sig.symbol}")')
lines.append('                break')

path.write_text(
    path.read_text(encoding='utf-8') + '\n'.join(lines),
    encoding='utf-8'
)
